// ── errors ───────────────────────────────────────────────────────────────────

export type HumanError = { summary: string; detail: string };

// Ordered: the first match wins, so the specific patterns come before the
// general ones (a 429 inside a JSON error is a rate limit, not a parse error).
const ERROR_RULES: { re: RegExp; summary: string | ((m: RegExpMatchArray) => string) }[] = [
  {
    re: /\b429\b|too many requests|rate.?limit/i,
    summary: "The AI service was busy and turned the request away. It will be retried.",
  },
  {
    re: /no backend available|no backends?|connection refused|ECONNREFUSED|dial tcp/i,
    summary: "No AI service was available to do this work.",
  },
  {
    re: /deadline exceeded|timed? ?out|timeout/i,
    summary: "The work took too long and was stopped.",
  },
  {
    re: /(?:status|HTTP|code)[ :=]*5\d\d\b|internal server error|bad gateway|service unavailable/i,
    summary: "The AI service returned an error.",
  },
  {
    re: /not a JSON object|invalid character|unexpected end of JSON|cannot unmarshal|invalid JSON/i,
    summary: "The AI service returned an answer in the wrong format.",
  },
  {
    re: /not segmented/i,
    summary: "Some pages could not be split into passages and were stored whole.",
  },
  {
    re: /missing (?:required )?field|required field|field .* (?:missing|required)/i,
    summary: "A required field was missing from the result.",
  },
  {
    re: /empty file|0-byte|zero bytes/i,
    summary: "The file is empty.",
  },
  {
    re: /encrypted|password/i,
    summary: "The file is password-protected and could not be read.",
  },
  {
    re: /(\w[\w.-]*)[^:\n]*:\s*exit status (\d+)/i,
    summary: (m) => `The ${m[1]} tool could not read this file.`,
  },
  {
    re: /exit status \d+/i,
    summary: "A file-reading tool could not read this file.",
  },
  {
    re: /\b404\b|not found/i,
    summary: "The item was not found.",
  },
];

// humanizeError maps a raw daemon or worker error to a plain one-line summary.
// `detail` is the raw text unchanged, for a "Technical details" disclosure.
// Unknown errors get a generic summary rather than the raw text, because the
// raw text is what this exists to keep out of the main view.
export function humanizeError(raw: string | undefined | null): HumanError {
  const detail = (raw ?? "").trim();
  if (!detail) return { summary: "", detail: "" };
  for (const rule of ERROR_RULES) {
    const m = detail.match(rule.re);
    if (m) {
      return { summary: typeof rule.summary === "function" ? rule.summary(m) : rule.summary, detail };
    }
  }
  return { summary: "Something went wrong with this item.", detail };
}
