// engineLabel names how a page's text was obtained. Unknown engines pass
// through, so a new one shows up as itself rather than as a blank.
export function engineLabel(engine: string | undefined): string {
  if (!engine) return "";
  return ENGINE_LABELS[engine] ?? engine;
}

const LANE_LABELS: Record<string, string> = { heavy: "Large", light: "Small" };

export function laneLabel(lane: string | undefined): string {
  if (!lane) return "";
  return LANE_LABELS[lane] ?? lane;
}

