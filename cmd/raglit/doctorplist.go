package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"os"
	"runtime"
	"strings"
)

// plistCheck is the installed launchd plist and the one install would write in
// its place. Mirrors unitCheck (doctorunit.go): parse → posixArgs → renderPlist → compare.
type plistCheck struct {
	path, have, want string
	reasons          []string
}

// parsePlist extracts the fields renderPlist writes from a plist XML string.
//
// The plist format uses sibling <key>/<value> pairs inside <dict>. The parser
// tracks the most recent <key> text and routes each value to the right field.
// It returns the daemon name (Label minus the com.iodesystems. prefix), the
// exec path, daemon arguments (after "daemon"), environment variables,
// RunAtLoad, and the log path.
func parsePlist(s string) (name, execPath string, daemonArgs, envs []string, runAtLoad bool, logPath string, err error) {
	dec := xml.NewDecoder(strings.NewReader(s))
	var lastKey, envKey string
	var inKey, inProgArgs, inEnvs bool
	var progArgs []string

	for {
		tok, derr := dec.Token()
		if derr != nil {
			break
		}
		switch t := tok.(type) {
		case xml.StartElement:
			switch t.Name.Local {
			case "key":
				inKey = true
			case "array":
				if lastKey == "ProgramArguments" {
					inProgArgs = true
				}
			case "dict":
				if lastKey == "EnvironmentVariables" {
					inEnvs = true
				}
			case "true":
				if lastKey == "RunAtLoad" {
					runAtLoad = true
				}
			case "false":
				if lastKey == "RunAtLoad" {
					runAtLoad = false
				}
			}
		case xml.EndElement:
			switch t.Name.Local {
			case "key":
				inKey = false
			case "array":
				inProgArgs = false
			case "dict":
				inEnvs = false
			}
		case xml.CharData:
			cs := string(bytes.TrimSpace(t))
			if cs == "" {
				continue
			}
			switch {
			case inKey:
				if inEnvs {
					envKey = cs
				} else {
					lastKey = cs
				}
			case inProgArgs:
				progArgs = append(progArgs, cs)
			case inEnvs:
				if envKey != "" {
					envs = append(envs, envKey+"="+cs)
					envKey = ""
				}
			default:
				switch lastKey {
				case "Label":
					name = strings.TrimPrefix(cs, "com.iodesystems.")
				case "StandardOutPath":
					logPath = cs
				}
			}
		}
	}

	if len(progArgs) < 2 {
		return "", "", nil, nil, false, "", fmt.Errorf("ProgramArguments is not `raglit daemon …`")
	}
	execPath = progArgs[0]
	if progArgs[1] != "daemon" {
		return "", "", nil, nil, false, "", fmt.Errorf("ProgramArguments is not `raglit daemon …`")
	}
	daemonArgs = progArgs[2:]
	return name, execPath, daemonArgs, envs, runAtLoad, logPath, nil
}

// plistCheckCore is the pure core: installed plist XML in, comparison result
// out. No file I/O, so it is testable on any platform.
//
// The comparison is: parse the plist, posixArgs the daemon arguments, render
// the "want" plist, and compare to the installed one. This mirrors checkUnit's
// parse → posixArgs → renderUnit → compare.
func plistCheckCore(installedPlistXML string) (want string, reasons []string, err error) {
	name, execPath, daemonArgs, envs, runAtLoad, logPath, parseErr := parsePlist(installedPlistXML)
	if parseErr != nil {
		return "", nil, parseErr
	}
	fixed := posixArgs(daemonArgs)
	want = renderPlist(name, execPath, fixed, envs, runAtLoad, logPath)
	if installedPlistXML == want {
		return want, nil, nil
	}
	if strings.Join(fixed, " ") != strings.Join(daemonArgs, " ") {
		reasons = append(reasons, "single-dash long flags: "+strings.Join(daemonArgs, " "))
	}
	if !strings.Contains(installedPlistXML, "Generated by `raglit service install`") {
		reasons = append(reasons, "not written by `raglit service install`")
	}
	if len(reasons) == 0 {
		reasons = append(reasons, "differs from what `raglit service install` writes now")
	}
	return want, reasons, nil
}

// checkPlist reads the installed launchd plist and compares it to what the
// installer would render now. ok is false when there is no plist (or not on
// darwin): nothing to check.
func checkPlist(name string) (c plistCheck, ok bool, err error) {
	if runtime.GOOS != "darwin" {
		return c, false, nil
	}
	c.path, err = launchdPlistPath(name)
	if err != nil {
		return c, false, err
	}
	b, err := os.ReadFile(c.path)
	if os.IsNotExist(err) {
		return c, false, nil
	} else if err != nil {
		return c, false, err
	}
	c.have = string(b)
	c.want, c.reasons, err = plistCheckCore(c.have)
	if err != nil {
		return c, true, err
	}
	return c, true, nil
}

// doctorPlist prints the plist check and, with fix, rewrites the plist and
// reloads launchd. The running daemon keeps its old arguments until restarted.
// Mirrors doctorUnit (doctorunit.go).
func doctorPlist(fix bool) {
	if runtime.GOOS != "darwin" {
		return
	}
	c, ok, err := checkPlist(serviceUnitName)
	if !ok && err == nil {
		fmt.Printf("\nLaunchAgent plist:\n  no service is installed\n")
		return
	}
	fmt.Printf("\nLaunchAgent plist (%s):\n", c.path)
	switch {
	case err != nil:
		fmt.Printf("  ✗ %v\n", err)
	case len(c.reasons) == 0:
		fmt.Println("  ✓ matches what `raglit service install` writes")
	case !fix:
		for _, r := range c.reasons {
			fmt.Printf("  ✗ %s\n", r)
		}
		fmt.Println("     fix:  raglit doctor --fix-plist   (rewrites the plist, then: raglit service restart)")
	default:
		if err := os.WriteFile(c.path, []byte(c.want), 0o644); err != nil {
			fmt.Printf("  ✗ rewrite: %v\n", err)
			return
		}
		launchdBootout(serviceUnitName)
		_ = launchctl("enable", launchdTarget(serviceUnitName)).Run()
		if err := launchdBootstrap(serviceUnitName, c.path); err != nil {
			fmt.Printf("  ✗ launchctl bootstrap: %v\n", err)
			return
		}
		fmt.Println("  ✓ rewritten; the daemon runs the old arguments until: raglit service restart")
	}
}
