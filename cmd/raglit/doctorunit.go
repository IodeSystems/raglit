package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

// The installed systemd unit, checked against what `service install` writes
// now (USER 2026-10-23). The unit outlives the binary: a unit written with
// single-dash long flags (`daemon -addr … -embed`) stops parsing when the
// flags go POSIX, and under Restart=on-failure that is a crash loop. So doctor
// reads the unit back, renders it again from its own exec path, daemon
// arguments and environment, and offers the rewrite.

// unitCheck is the installed unit and the one install would write in its place.
type unitCheck struct {
	path, have, want string
	reasons          []string
}

// singleDashLong matches a long flag written with one dash: -addr, -embed=true.
var singleDashLong = regexp.MustCompile(`^-[a-z][a-z0-9-]+(=.*)?$`)

// posixArgs rewrites single-dash long flags to double-dash. Values are left as
// they are: a value never looks like -word in a daemon argument list.
func posixArgs(args []string) []string {
	out := make([]string, len(args))
	for i, a := range args {
		if singleDashLong.MatchString(a) {
			a = "-" + a
		}
		out[i] = a
	}
	return out
}

// checkUnit reads ~/.config/systemd/user/<name>.service. ok is false when
// there is no unit (or not on Linux): nothing to check.
func checkUnit(name string) (c unitCheck, ok bool, err error) {
	if runtime.GOOS != "linux" {
		return c, false, nil
	}
	dir, err := unitDir()
	if err != nil {
		return c, false, err
	}
	c.path = filepath.Join(dir, name+".service")
	b, err := os.ReadFile(c.path)
	if os.IsNotExist(err) {
		return c, false, nil
	} else if err != nil {
		return c, false, err
	}
	c.have = string(b)
	execPath, args, envs, err := parseUnit(c.have)
	if err != nil {
		return c, true, err
	}
	fixed := posixArgs(args)
	c.want = renderUnit(execPath, fixed, envs)
	if c.have == c.want {
		return c, true, nil
	}
	if strings.Join(fixed, " ") != strings.Join(args, " ") {
		c.reasons = append(c.reasons, "single-dash long flags: "+strings.Join(args, " "))
	}
	if !strings.Contains(c.have, "# Generated by `raglit service install`") {
		c.reasons = append(c.reasons, "not written by `raglit service install`")
	}
	if len(c.reasons) == 0 {
		c.reasons = append(c.reasons, "differs from what `raglit service install` writes now")
	}
	return c, true, nil
}

// parseUnit takes the exec path, daemon arguments and Environment= lines back
// out of a unit, so renderUnit can write the same daemon again.
func parseUnit(unit string) (execPath string, args, envs []string, err error) {
	var start string
	for _, l := range strings.Split(unit, "\n") {
		switch {
		case strings.HasPrefix(l, "ExecStart="):
			start = strings.TrimPrefix(l, "ExecStart=")
		case strings.HasPrefix(l, "Environment="):
			envs = append(envs, strings.TrimPrefix(l, "Environment="))
		}
	}
	words, err := splitUnitWords(start)
	if err != nil {
		return "", nil, nil, err
	}
	if len(words) < 2 || words[1] != "daemon" {
		return "", nil, nil, fmt.Errorf("ExecStart is not `raglit daemon …`: %q", start)
	}
	return words[0], words[2:], envs, nil
}

// splitUnitWords undoes quoteUnit: words split on spaces, "…" groups a word,
// and inside quotes \\ and \" are escapes. %% is a literal %.
func splitUnitWords(s string) ([]string, error) {
	var words []string
	var w strings.Builder
	inWord, quoted := false, false
	for i := 0; i < len(s); i++ {
		ch := s[i]
		switch {
		case quoted && ch == '\\' && i+1 < len(s):
			i++
			w.WriteByte(s[i])
		case ch == '"':
			quoted = !quoted
			inWord = true
		case !quoted && (ch == ' ' || ch == '\t'):
			if inWord {
				words = append(words, w.String())
				w.Reset()
				inWord = false
			}
		case ch == '%' && i+1 < len(s) && s[i+1] == '%':
			i++
			w.WriteByte('%')
			inWord = true
		default:
			w.WriteByte(ch)
			inWord = true
		}
	}
	if quoted {
		return nil, fmt.Errorf("unterminated quote in %q", s)
	}
	if inWord {
		words = append(words, w.String())
	}
	return words, nil
}

// doctorUnit prints the unit check and, with fix, rewrites the unit and
// reloads systemd. The running daemon keeps its old arguments until restarted.
func doctorUnit(fix bool) {
	c, ok, err := checkUnit(serviceUnitName)
	if !ok && err == nil {
		return
	}
	fmt.Printf("\nservice unit (%s):\n", c.path)
	switch {
	case err != nil:
		fmt.Printf("  ✗ %v\n", err)
	case len(c.reasons) == 0:
		fmt.Println("  ✓ matches what `raglit service install` writes")
	case !fix:
		for _, r := range c.reasons {
			fmt.Printf("  ✗ %s\n", r)
		}
		fmt.Println("     fix:  raglit doctor --fix-unit   (rewrites the unit, then: raglit service restart)")
	default:
		if err := os.WriteFile(c.path, []byte(c.want), 0o644); err != nil {
			fmt.Printf("  ✗ rewrite: %v\n", err)
			return
		}
		if err := systemctl("daemon-reload").Run(); err != nil {
			fmt.Printf("  ✗ systemctl --user daemon-reload: %v\n", err)
			return
		}
		fmt.Println("  ✓ rewritten; the daemon runs the old arguments until: raglit service restart")
	}
}
